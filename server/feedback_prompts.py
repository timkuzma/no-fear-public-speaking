def question_prompt():
    return DATA_RULE + coaching_context.QUESTION_GUIDANCE + (
        'Составь ровно три разных вопроса к сохранённой речи (segments с kind=speech). '
        'Каждый вопрос уточняет конкретную мысль, утверждение или пример из выбранной evidence. '
        'Не приписывай технологии, планы, числа и аргументы, которых нет в речи. '
        'Не задавай общий вопрос ко всей теме или три переформулировки одного вопроса. '
        'Не проси воспроизвести факт, который уже прямо назван в речи: если сказано «рядом '
        'со школой», не спрашивай «где?». Уточняй ещё не раскрытое основание, условие, смысл '
        'или следствие именно сказанной мысли, не достраивая неизвестные планы и результаты. '
        'Обращайся к выступающему напрямую как слушатель встречи: «почему вы…», а не '
        '«по мнению автора…». Неполная речь не оправдывает выдуманную предпосылку. '
        'Короткая речь: разрешено три разных уточнения одной мысли с одним evidence_id. '
        'Выбирай ровно один существующий evidence_id, относящийся именно к мысли этого '
        'вопроса. Не повторяй один id для разных мыслей только ради заполнения поля. '
        'Формулируй вопрос естественно, без длинного пересказа и вводного «Вы сказали…». '
        'Не вставляй цитаты и кавычки в текст вопроса: задавай сам вопрос о выбранной мысли. '
        f'Текст вопроса: 8–{CAPS["question"]} символов. Ровно ключ questions, '
        'массив ровно из трёх объектов с ключами text,evidence_id. '
        'Пример: речь «Я хочу подготовиться к собеседованию» позволяет уточнить, '
        'к какому собеседованию, какую часть хочется отрепетировать и что хотелось бы получить '
        'от подготовки; не позволяет утверждать, что собеседование уже назначено. '
        'Последняя проверка каждого объекта: выбранный id содержит основание именно '
        'этого вопроса; дословные слова находятся в этой цитате; один вопрос не соединяет '
        'две задачи; ответ ещё не дан в речи.'
    )


def report_prompt():
    return DATA_RULE + coaching_context.GENERAL_FEEDBACK + (
        'Порядок работы: прочитай всю речь и ответы, выбери конкретный evidence_id для '
        'каждого полезного наблюдения, затем сформулируй вывод только о выбранном отрывке. '
        'Одно слово или приветствие не подтверждает общий вывод о всей речи. '
        'speech — исходное выступление; answer — ответ на свой saved_question. '
        'Вопросы являются контекстом, а не произнесённым доказательством. Не переноси '
        'информацию из ответа в исходное выступление. repeat_focus — выбранное ранее '
        'действие, не новая норма и не доказательство о нынешней речи. '
        'Критерии пользователя — отдельная часть отчёта. Не подменяй ими общий анализ. '
        'Сервер сам покажет выбранную цитату рядом с наблюдением. Поэтому observation '
        'и action пиши своими словами БЕЗ кавычек, повторного цитирования речи и '
        'цитирования контрольных вопросов. Описывай конкретный приём или трудность, '
        'а не дублируй текст выступления. '
        'Речь не обязана следовать одному шаблону: оценивай, как сформулированные мысли '
        'связаны между собой и могут быть поняты, не требуя недостающих фактов о мире. '
        'Каждое фактическое утверждение в observation должно подтверждаться выбранной '
        'цитатой. Для связи соседних предложений выбери sN-pM, включающий оба. '
        'Не утверждай отсутствие элемента во всей речи по одной цитате. '
        'Не объявляй обычные вводные слова ошибкой и не делай выводов об уверенности. '
        'Не повторяй один диагноз в двух рекомендациях. '
        'action: одно точное действие на следующую попытку, связанное с цитатой; '
        'при необходимости добавь признак, по которому говорящий проверит правку. '
        'Запрещены готовые новые фразы и примеры в action/observation. Содержание правки '
        'выбирает сам говорящий. example всегда null. Все дословно упомянутые слова '
        'внутри кавычек должны присутствовать в выбранной evidence. '
        'Факты из других частей речи не обосновываются этой цитатой. '
        'Возможное влияние на понимание описывай условно, без реальных реакций слушателей. '
        'Короткому тексту нужен более короткий разбор. Число пунктов не квота. '
        f'strengths: 0–{CAPS["strengths"]}; recommendations: 0–{CAPS["recommendations"]}. '
        'primary_recommendation_index — индекс наиболее полезной рекомендации с нуля '
        'или null при отсутствии обоснованного фокуса. Не создавай отдельный insight. '
        'criteria: ровно один объект на каждый requested_criteria, без новых критериев. '
        'status: met|partial|not_met|unknown; basis: present|absent|unknown. '
        'present требует evidence_id и основания в самой цитате; not_met/partial '
        'допустимы для явного противоречия заданной норме, а не предполагаемого пропуска. '
        'Если критерий задаёт только область внимания, не придумывай условие успеха. '
        'Психологическая уверенность, голос и жесты не наблюдаются в тексте. '
        'Нечёткий критерий, отсутствие, неполнота или сомнение в распознавании: '
        'status=unknown,basis=unknown,evidence_id=null с краткой причиной. '
        'Capture completeness не доказывает лексическую точность ASR. '
        f'Максимум символов: title {CAPS["title"]}, observation {CAPS["observation"]}, '
        f'action {CAPS["action"]}, reason {CAPS["reason"]}. '
        'Ровно ключи strengths,recommendations,primary_recommendation_index,criteria. '
        'strengths объекты: title,observation,evidence_id. recommendations объекты: '
        'title,observation,action,example,evidence_id. criteria объекты: '
        'criterion_id,status,basis,reason,evidence_id. Без дополнительных ключей. '
        'Следующий синтетический пример показывает формат и отделение общего разбора '
        'от одного пользовательского критерия. Не копируй из него факты и id: выбирай '
        'только evidence текущей речи. '
    ) + json.dumps([REPORT_EXAMPLES[-1]], ensure_ascii=False, separators=(',', ':')) + (
        'Перед выдачей сверь КАЖДЫЙ пункт с текстом ровно выбранной evidence. '
        'Нельзя объяснять этот пункт фактами из других цитат, даже если они есть в речи. '
        'Если связь требует двух отдалённых фрагментов, выбери более узкое наблюдение '
        'или убери пункт. Не хвали ту же причинную связь, которую называешь неясной '
        'в рекомендации. Лучше один обоснованный пункт, чем второй со спорной опорой. '
        'Не критикуй понятный итог за то, что он обобщает уже рассказанную историю: '
        'заключение не обязано снова перечислять эпизоды. Не требуй повторно раскрыть '
        'то, что уже объяснено рядом. Оставляй только рекомендации с конкретным '
        'обоснованным затруднением, а не гипотетической возможностью что-нибудь добавить. '
        'Все слова в кавычках в observation и action сверяй посимвольно с выбранной '
        'цитатой; не изменяй окончания, не цитируй свои термины как слова говорящего.'
    )

